package hr.foi.popapp

import junit.framework.TestCase.assertEquals
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.junit.Ignore
import org.junit.Test

@Ignore("Demo only: raw OkHttp code generated by Postman, hits the live server")
class RegisterServiceTest {
    @Test
    fun testRegistrationRoute() {
        val existingUsername = "ihorvat"

        val url = "https://ase.foi.hr/pop/api/v2/auth/register"
        val jsonForExistingUser = "{\n" +
                "    \"first_name\": \"SomeName\",\n" +
                "    \"last_name\": \"SomeSurname\",\n" +
                "    \"username\": \"$existingUsername\",\n" +
                "    \"email\": \"someemail@ase.foi.hr\",\n" +
                "    \"password\": \"test123\",\n" +
                "    \"role\": \"buyer\"\n" +
                "}"
        val client = OkHttpClient()

        val requestBody = jsonForExistingUser.toRequestBody("application/json".toMediaType())
        val request = Request.Builder()
            .url(url)
            .post(requestBody)
            .build()

        client.newCall(request).execute().use { response ->
            assertEquals(400, response.code)
        }
    }
}